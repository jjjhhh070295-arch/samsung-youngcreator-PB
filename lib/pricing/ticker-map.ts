/**
 * 한국 주식 종목명 → 종목코드 정적 매핑
 * KOSPI 200 + 주요 KOSDAQ + 인기 ETF 포함
 *
 * 정규화 함수 normalizeKrName()으로 비교 (공백·주식유형 접미사 무시).
 */

/** 종목명 정규화: 공백·특수문자·우/ETF 구분기호 제거 후 소문자 */
export function normalizeKrName(name: string): string {
  return name
    .toLowerCase()
    .replace(/\s+/g, "")                       // 공백 제거
    .replace(/\./g, "")                         // 마침표 제거
    .replace(/[()（）\[\]]/g, "")              // 괄호 제거
    .replace(/보통주$/g, "")                    // "보통주" 접미사
    .replace(/주식$/g, "")                      // "주식" 접미사
    .replace(/ETF$/gi, "");                     // ETF 접미사
}

